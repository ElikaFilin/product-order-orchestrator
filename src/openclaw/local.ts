/**
 * OpenClaw runs from this project: the repo's pinned `openclaw` package, its state and config under
 * .runtime/openclaw/, and the secrets from the repo's .env (loaded into the process environment by the pnpm
 * scripts). Nothing is installed globally and ~/.openclaw is never used.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT_DIR, runtimeDir } from '../config/env.js';

export const GATEWAY_PORT = 18789;

export interface LocalOpenClaw {
  /** OPENCLAW_STATE_DIR: sessions, transcripts, the plugin's order state. */
  stateDir: string;
  /** OPENCLAW_CONFIG_PATH: generated by `pnpm openclaw:config`. */
  configPath: string;
  /** The gateway token (loopback only), generated once. */
  tokenFile: string;
  /** The repo's openclaw CLI. */
  cli: string;
}

export function localOpenClaw(): LocalOpenClaw {
  const home = runtimeDir('openclaw');
  return {
    stateDir: path.join(home, 'state'),
    configPath: path.join(home, 'openclaw.json'),
    tokenFile: path.join(home, 'gateway-token'),
    cli: path.join(ROOT_DIR, 'node_modules', 'openclaw', 'openclaw.mjs'),
  };
}

/** The gateway token, created on first use (mode 0600). */
export function gatewayToken(paths: LocalOpenClaw = localOpenClaw()): string {
  if (existsSync(paths.tokenFile)) return readFileSync(paths.tokenFile, 'utf8').trim();
  mkdirSync(path.dirname(paths.tokenFile), { recursive: true, mode: 0o700 });
  const token = randomBytes(24).toString('hex');
  writeFileSync(paths.tokenFile, `${token}\n`, { mode: 0o600 });
  return token;
}

/** The environment every OpenClaw command of this project runs with (the .env secrets are already in `base`). */
export function openclawEnv(base: NodeJS.ProcessEnv = process.env, paths: LocalOpenClaw = localOpenClaw()): NodeJS.ProcessEnv {
  return {
    ...base,
    OPENCLAW_STATE_DIR: paths.stateDir,
    OPENCLAW_CONFIG_PATH: paths.configPath,
    OPENCLAW_GATEWAY_TOKEN: gatewayToken(paths),
    // The version is pinned in package.json: no update checks or self-updates.
    OPENCLAW_NO_AUTO_UPDATE: '1',
  };
}
